using AlphaLab.Evaluation.Numerics;

namespace AlphaLab.Evaluation.Tests;

/// <summary>
/// The k-regressor HAC OLS (checkpoint 6.6), which DESIGN_IMPROVEMENTS §1.4's five-factor attribution
/// regression needs and which nothing in the repo could do — `NeweyWest.Ols` is hard-coded to one.
///
/// **THE ORACLE IS THE CODE IT GENERALIZES.** At k=1 the general matrix path must reproduce
/// `NeweyWest.Ols`, which inverts a 2×2 in closed form and hand-expands its sandwich. That closed form is
/// already covered by its own fixtures, so it is a known-good reference — and a Cholesky/inverse/sandwich
/// chain cannot agree with it to twelve significant figures by accident. Any algebra error anywhere in the
/// general path shows up here.
///
/// **THE TOLERANCE IS A NUMBER, NOT THE WORD "TIGHT".** `1e-12` relative: the two routes compute the same
/// quantity in a different order, so they differ by floating-point association only, while an actual
/// mistake — a transposed index, a dropped weight, a missing Γ_kᵀ — moves a result far beyond it. If this
/// ever needs widening, THAT is a finding about the numerics and not a licence to edit the constant.
/// </summary>
public class HacOlsTests
{
    private const double RelTol = 1e-12;

    private static void AssertRelClose(double expected, double actual, string what)
    {
        var scale = Math.Max(Math.Abs(expected), 1e-300);
        var rel = Math.Abs(actual - expected) / scale;
        Assert.True(rel <= RelTol, $"{what}: expected {expected:R}, got {actual:R} (relative {rel:E3} > {RelTol:E3})");
    }

    /// <summary>Deterministic, autocorrelated, and NOT generated by the code under test: an AR(1)-ish
    /// regressor with a genuine slope plus serially-correlated noise, so the HAC correction actually bites
    /// (with i.i.d. residuals the lagged Γ terms vanish and the fixture would pass on a broken meat matrix).</summary>
    private static (double[] Y, double[] X) Series(int n, int seed)
    {
        var rng = new Random(seed);
        var x = new double[n];
        var y = new double[n];
        double xPrev = 0, ePrev = 0;
        for (var i = 0; i < n; i++)
        {
            var xi = 0.7 * xPrev + (rng.NextDouble() - 0.5);
            var ei = 0.6 * ePrev + (rng.NextDouble() - 0.5) * 0.3;   // autocorrelated residual
            x[i] = xi;
            y[i] = 0.0004 + 1.15 * xi + ei;
            xPrev = xi; ePrev = ei;
        }
        return (y, x);
    }

    // ---------- the oracle ----------

    [Theory]
    [InlineData(60, 5, 1)]
    [InlineData(252, 21, 2)]
    [InlineData(1000, 21, 3)]
    // n <= lag, so maxLag = n-1 = 11 while the WEIGHT denominator stays the caller's 21. This case exists
    // because a falsifier found the hole: an earlier (n=37, lag=21) never truncated — 37 > 22 — so
    // maxLag == lag and swapping the denominator to maxLag changed nothing and stayed green. The
    // convention is only under test when the two actually differ.
    [InlineData(12, 21, 4)]
    [InlineData(500, 0, 5)]     // lag 0: no meat-matrix lag terms at all
    public void FR13_D41_AtOneRegressor_TheGeneralPathReproducesNeweyWestOls(int n, int lag, int seed)
    {
        var (y, x) = Series(n, seed);

        var oracle = NeweyWest.Ols(y, x, lag);
        var general = HacOls.Fit(y, [x], lag);

        AssertRelClose(oracle.Alpha, general.Alpha, "Alpha");
        AssertRelClose(oracle.Beta, general.Betas[0], "Beta");
        AssertRelClose(oracle.AlphaSe, general.AlphaSe, "AlphaSe");
        AssertRelClose(oracle.BetaSe, general.BetaSes[0], "BetaSe");
        Assert.Equal(oracle.N, general.N);
        Assert.Equal(oracle.Lag, general.Lag);   // pins Math.Min(lag, n-1) exactly
    }

    [Fact]
    public void FR13_D41_TheTStatConventionMatchesTheOracle()
    {
        var (y, x) = Series(252, 11);
        AssertRelClose(NeweyWest.Ols(y, x, 21).AlphaT, HacOls.Fit(y, [x], 21).AlphaT, "AlphaT");
    }

    // ---------- the general case ----------

    /// <summary>With EXACTLY collinear columns the design is rank-deficient and there is no unique answer.
    /// Fail loud (the `NeweyWest.Ols` posture), never a fit nobody can interpret.</summary>
    [Fact]
    public void FR13_D41_ACollinearRegressorSet_IsRefused_NotFitted()
    {
        var (y, x) = Series(300, 7);
        var doubled = x.Select(v => 2.0 * v).ToArray();   // x2 = 2·x1 exactly

        var ex = Assert.Throws<ArgumentException>(() => HacOls.Fit(y, [x, doubled], 21));
        Assert.Contains("Degenerate design", ex.Message, StringComparison.Ordinal);
    }

    /// <summary>
    /// A constant regressor is EXACTLY singular, and the two paths disagree about it — which is
    /// **finding 442**, not a tolerance to tune.
    ///
    /// `NeweyWest.Ols` guards with `Math.Abs(det) &lt; 1e-12`, an ABSOLUTE epsilon on `det = n·Σx² − (Σx)²`,
    /// a quantity that scales like n²·x². The true determinant here is zero, but floating-point rounding
    /// leaves a residue far above 1e-12, so the guard does not fire and the closed form returns
    /// `β = (n·Σxy − Σx·Σy)/det` — **a slope divided by pure noise, reported as a fit, silently**. It
    /// gets WORSE with more data: measured at |det| = 6.0E−11 (n=300) and 1.2E−06 (n=5000) for x ≡ 0.42,
    /// yielding β = 0.909 and 0.310 respectively. It catches the singular case only when the arithmetic
    /// happens to cancel exactly (x ≡ 1.0 gives det exactly 0).
    ///
    /// This fixture therefore pins the DIFFERENCE rather than asserting agreement: the general path's
    /// pivot floor is relative to the column's own scale and refuses; the oracle's is not and does not.
    /// `NeweyWest.cs` is deliberately NOT corrected here — that would change the arithmetic under the
    /// gate, the MDE and the monitor's alpha t-stat, which needs its own measured divergence and its own
    /// commit. The finding carries that as its trigger. If someone later fixes the oracle, THIS TEST GOES
    /// RED and points at the finding, which is the intended way to learn that it landed.
    /// </summary>
    [Fact]
    public void FR13_D41_AConstantRegressor_IsRefusedHere_ButNotByTheOracle_finding442()
    {
        var (y, _) = Series(300, 8);
        var flat = new double[300];
        Array.Fill(flat, 0.42);

        // The general path refuses it — the behaviour `NeweyWest.Ols` documents but does not deliver.
        var ex = Assert.Throws<ArgumentException>(() => HacOls.Fit(y, [flat], 21));
        Assert.Contains("Degenerate design", ex.Message, StringComparison.Ordinal);

        // The oracle does NOT refuse it, and what it returns is arithmetic on rounding noise.
        var slipped = NeweyWest.Ols(y, flat, 21);
        Assert.True(double.IsFinite(slipped.Beta),
            "finding 442 assumes the oracle returns a finite fabricated slope; a NaN/∞ here means the " +
            "absolute-epsilon guard now behaves differently and the finding needs re-measuring.");

        // The exactly-cancelling case is the one it does catch — which is why the defect looks absent
        // under a casually-chosen fixture value.
        var ones = new double[300];
        Array.Fill(ones, 1.0);
        Assert.Throws<ArgumentException>(() => NeweyWest.Ols(y, ones, 21));
        Assert.Throws<ArgumentException>(() => HacOls.Fit(y, [ones], 21));
    }

    /// <summary>The five-regressor shape §1.4 actually specifies. Constructed so the answer is known:
    /// y is built from the factors with fixed loadings plus autocorrelated noise, so each β must land near
    /// its planted value. Loose bounds on purpose — this pins that the SOLVER works at k=5, while the
    /// oracle fixture is what pins the arithmetic exactly.</summary>
    [Fact]
    public void FR13_D41_FiveRegressors_RecoverThePlantedLoadings()
    {
        const int n = 2000;
        var rng = new Random(99);
        double[][] f = [new double[n], new double[n], new double[n], new double[n], new double[n]];
        var y = new double[n];
        double[] planted = [0.92, 0.31, -0.15, 0.44, 0.08];

        var ePrev = 0.0;
        for (var t = 0; t < n; t++)
        {
            var mean = 0.0;
            for (var j = 0; j < 5; j++)
            {
                f[j][t] = (rng.NextDouble() - 0.5) * (1.0 + j * 0.1);
                mean += planted[j] * f[j][t];
            }
            var e = 0.5 * ePrev + (rng.NextDouble() - 0.5) * 0.05;
            y[t] = 0.0002 + mean + e;
            ePrev = e;
        }

        var fit = HacOls.Fit(y, f, 21);

        Assert.Equal(5, fit.Betas.Count);
        Assert.Equal(5, fit.BetaSes.Count);
        for (var j = 0; j < 5; j++)
        {
            Assert.True(Math.Abs(fit.Betas[j] - planted[j]) < 0.02,
                $"β{j}: expected ≈{planted[j]}, got {fit.Betas[j]:F4}");
            Assert.True(fit.BetaSes[j] > 0, $"β{j} SE must be positive, got {fit.BetaSes[j]:E3}");
        }
        Assert.Equal(21, fit.Lag);
    }

    [Fact]
    public void FR13_D41_TooFewObservationsForTheRegressorCount_IsRefused()
    {
        // 5 regressors ⇒ p = 6 ⇒ needs at least 7 observations.
        var y = new double[6];
        double[][] f = [new double[6], new double[6], new double[6], new double[6], new double[6]];
        var ex = Assert.Throws<ArgumentException>(() => HacOls.Fit(y, f, 5));
        Assert.Contains("at least 7", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void FR13_D41_ARegressorOfTheWrongLength_IsRefused()
    {
        var (y, x) = Series(100, 3);
        var shortOne = x.Take(99).ToArray();
        Assert.Throws<ArgumentException>(() => HacOls.Fit(y, [x, shortOne], 21));
    }

    /// <summary>Intercept-only (k = 0) is a legitimate degenerate case: α is the sample mean and its HAC SE
    /// is the long-run variance of y, so `LongRunVariance` — the OTHER member of the shared convention —
    /// becomes a second, independent oracle for the meat matrix.</summary>
    [Fact]
    public void FR13_D41_InterceptOnly_MatchesTheLongRunVarianceConvention()
    {
        var (y, _) = Series(500, 21);
        const int lag = 21;

        var fit = HacOls.Fit(y, [], lag);

        AssertRelClose(y.Average(), fit.Alpha, "Alpha == sample mean");
        // Var(mean) = σ²_LR / n under the same Bartlett convention.
        var expectedSe = Math.Sqrt(NeweyWest.LongRunVariance(y, lag) / y.Length);
        AssertRelClose(expectedSe, fit.AlphaSe, "AlphaSe == sqrt(LRV/n)");
    }
}
